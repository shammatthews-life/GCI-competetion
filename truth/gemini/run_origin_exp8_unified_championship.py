            p_trn = np.zeros(len(X_tr), dtype=float)
            for in_trn, in_val in inner_cv.split(X_tr, y_trn):
                in_mask = valid_mask.iloc[in_trn]
                reg_in = Ridge(alpha=100.0)
                reg_in.fit(X_tr.iloc[in_trn].loc[in_mask, pred_feats].fillna(0.0), X_tr.iloc[in_trn].loc[in_mask, col_tgt])
