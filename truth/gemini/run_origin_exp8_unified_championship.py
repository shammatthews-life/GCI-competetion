def to_probit(p_arr):
    r = rankdata(p_arr) / (len(p_arr) + 1.0)
    return norm.ppf(np.clip(r, 1e-6, 1.0 - 1e-6))

z_oof_mat = np.column_stack([to_probit(oof_dict[m]) for m in models])
z_te_mat = np.column_stack([to_probit(test_dict[m]) for m in models])

# Equal-Weight Baseline
eq_weights = np.ones(len(models)) / len(models)
oof_eq_probit = z_oof_mat @ eq_weights
auc_eq = roc_auc_score(y_train, oof_eq_probit)
print(f"\n[+] Equal-Weight Probit Blend Pooled OOF AUC: {auc_eq:.6f}")

# Convex Optimization
def neg_auc_loss(w):
    w_norm = np.maximum(w, 0.0)
    if w_norm.sum() == 0:
        return 0.0
    w_norm /= w_norm.sum()
    pred = z_oof_mat @ w_norm
    return -roc_auc_score(y_train, pred)

res = minimize(neg_auc_loss, eq_weights, method="Nelder-Mead", options={"maxiter": 800, "disp": False})
opt_weights = np.maximum(res.x, 0.0)
opt_weights /= opt_weights.sum()

oof_opt_probit = z_oof_mat @ opt_weights
auc_opt = roc_auc_score(y_train, oof_opt_probit)
print(f"[+] Optimal Convex Probit Blend Pooled OOF AUC : {auc_opt:.6f} (+{(auc_opt - auc_eq)*10000:+.1f} bps vs equal)")

